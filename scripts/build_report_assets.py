"""Copy the final report evidence into the tracked folder report_assets/ (copies only).

Run with:  uv run python scripts/build_report_assets.py
Sources are only read. No Mendeley video or frame is copied, and nothing from
outputs/demo_videos/ is copied. Writes report_assets/MANIFEST.md with sizes, sha256 and the
files that were looked for but not found.
"""

import hashlib
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ML = ROOT / "outputs" / "ml"
DEST = ROOT / "report_assets"
LIMIT_MB = 25

# (source, destination folder inside report_assets)
FILES = [
    (ML / "results" / "final_test_table.md", "tables"),
    (ML / "results" / "final_test_table.csv", "tables"),
    (ML / "results" / "final_val_table.md", "tables"),
    (ML / "results" / "detection_metrics.md", "tables"),
    (ML / "report_numbers.json", "evidence"),
    (ML / "audit.json", "evidence"),
    (ML / "chosen_settings.json", "evidence"),
    (ML / "requirements_check.md", "evidence"),
    (ML / "figure_index.md", "evidence"),
    (ROOT / "outputs" / "reproduce" / "pipeline_runtimes.tsv", "evidence"),
    # Video demo: text files only (no video, no frame).
    (ROOT / "outputs" / "demo_cache" / "demo_selection.json", "video_demo"),
    (ROOT / "outputs" / "demo_cache" / "diagnostics.md", "video_demo"),
    (ROOT / "outputs" / "demo_cache" / "threshold_summary.md", "video_demo"),
    (ROOT / "outputs" / "demo_cache" / "threshold_summary.csv", "video_demo"),
]
# Colab training outputs, if they were downloaded into the repo or ~/Downloads.
COLAB_NAMES = ["results.csv", "results.png", "confusion_matrix.png", "args.yaml"]
COLAB_PLACES = [
    ROOT / "outputs" / "yolo_runs",
    ROOT / "outputs" / "yolo_colab",
    Path.home() / "Downloads",
]


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    if DEST.exists():
        shutil.rmtree(DEST)  # generated folder: rebuilt from the sources every time
    copied, missing = [], []
    figures = sorted((ML / "figures").glob("fig_*.png"))  # the numbered final figures
    for source, folder in [(p, "figures") for p in figures] + FILES:
        if not source.is_file():
            missing.append(str(source.relative_to(ROOT)))
            continue
        target = DEST / folder / source.name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
        copied.append(target)
    for name in COLAB_NAMES:
        found = [p for place in COLAB_PLACES if place.is_dir() for p in place.rglob(name)]
        if found:
            target = DEST / "colab" / name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(found[0], target)
            copied.append(target)
        else:
            missing.append(f"Colab {name} (not found in outputs/yolo_runs, outputs/yolo_colab "
                           "or ~/Downloads)")
    total = sum(p.stat().st_size for p in copied)
    lines = [
        "# report_assets manifest",
        "",
        "Generated by `scripts/build_report_assets.py` (copies of files under `outputs/`).",
        "",
        f"Files: {len(copied)}. Total size: {total / 1e6:.2f} MB.",
        "",
        "| file | bytes | sha256 |",
        "|---|---|---|",
    ]
    lines += [
        f"| {p.relative_to(DEST)} | {p.stat().st_size} | {sha256(p)[:16]} |" for p in copied
    ]
    lines += ["", "Not found (not copied):", ""] + [f"- {m}" for m in missing or ["none"]]
    (DEST / "MANIFEST.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    if total > LIMIT_MB * 1e6:
        raise SystemExit(f"report_assets is {total / 1e6:.2f} MB, above {LIMIT_MB} MB")


if __name__ == "__main__":
    main()
